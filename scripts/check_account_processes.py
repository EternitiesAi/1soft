#!/usr/bin/env python3
"""Native account onboarding/rotation in four application processes.

ABCI requests are scripted, not generated by a consensus engine. The public
report NEVER claims validator voting and never exports private fixture keys.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import time

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'src'))
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from native_core import NativeLedger, public, address, sign, canonical, accept_account_key
from abci_wire import Client


def run(destination: Path):
    sponsor, merchant, resident, worker, new_key, agent_a, agent_b = (
        Ed25519PrivateKey.generate() for _ in range(7))
    sid,mid,rid,wid = [address(public(k)) for k in (sponsor,merchant,resident,worker)]
    genesis={'protocol_version':2,'chain_id':'eternities-scripted-lifecycle-v2','asset':'DEV','fee':10,
        'allocations':[{'public_key':public(sponsor),'units':1_000_000},
                       {'public_key':public(merchant),'units':0}]}
    model=NativeLedger(':memory:',genesis)
    def tx(key,sender,nonce,op,grant='',incoming=None):
        body=model.body(sender,nonce,op,grant_id=grant)
        if incoming is not None:body=accept_account_key(incoming,body)
        return canonical(sign(key,body))
    opened=[]
    for nonce,(key,units) in enumerate(((resident,100_000),(worker,80_000))):
        opened.append(tx(sponsor,sid,nonce,{'type':'open_account','public_key':public(key),
                         'units':units,'acceptance':''},incoming=key))
    def grant(key,owner,nonce,label,agent,cap):
        return tx(key,owner,nonce,{'type':'grant','id':label,'public_key':public(agent),
            'cap':cap,'expires':1000,'recipients':[mid]})
    def pay(key,owner,nonce,units,label=''):
        return tx(key,owner,nonce,{'type':'transfer','to':mid,'units':units},label)
    block1=opened+[
        grant(resident,rid,0,'raven',agent_a,20_050),
        grant(worker,wid,0,'raven',agent_b,10_020),
        pay(agent_a,rid,0,12_000,'raven'),pay(agent_b,wid,0,5_000,'raven')]
    rotation=tx(resident,rid,1,{'type':'rotate_key','public_key':public(new_key),'acceptance':''},incoming=new_key)
    block2=[rotation,pay(agent_b,wid,1,100,'raven'),pay(new_key,rid,2,1_000),
            grant(new_key,rid,3,'raven-v2',agent_a,2_020),pay(agent_a,rid,0,1_000,'raven-v2')]
    stale_owner=pay(resident,rid,4,1)
    stale_agent=pay(agent_a,rid,1,1,'raven')
    duplicate_open=tx(sponsor,sid,2,{'type':'open_account','public_key':public(resident),
                                   'units':100_000,'acceptance':''},incoming=resident)
    model.close()
    report={'schema':1,'mode':'SCRIPTED native-account ABCI lifecycle, NOT consensus',
            'consensus_engine_running':False,'validator_votes_tested':False,
            'private_keys_exported':False,'genesis':genesis,'checks':[],'blocks':[]}
    def checked(name,condition,details=None):
        report['checks'].append({'name':name,'passed':bool(condition),'details':details})
        if not condition:raise AssertionError(name)
    procs={};clients={};logs={}
    with tempfile.TemporaryDirectory(prefix='etn-account-') as directory:
        runtime=Path(directory);g=runtime/'genesis.json';g.write_bytes(canonical(genesis))
        def start(i):
            node=runtime/str(i);node.mkdir(mode=0o700,exist_ok=True)
            sock=node/'a.sock'
            if sock.exists():sock.unlink()  # owned disposable node, only after its process was reaped
            log=open(node/'server.log','ab');logs[i]=log
            procs[i]=subprocess.Popen([sys.executable,str(ROOT/'scripts/serve_abci.py'),
                '--db',str(node/'app.sqlite'),'--socket',str(sock),'--genesis',str(g)],
                cwd=ROOT,stdout=log,stderr=log)
            deadline=time.monotonic()+10
            while time.monotonic()<deadline:
                if procs[i].poll() is not None:raise RuntimeError((node/'server.log').read_text())
                try:
                    clients[i]=Client(str(sock));clients[i].call('info');return
                except (FileNotFoundError,ConnectionRefusedError,ConnectionError):time.sleep(.02)
            raise TimeoutError('account application startup timeout')
        def stop(i,kill=False):
            if i in clients:clients.pop(i).close()
            p=procs.pop(i)
            if p.poll() is None:
                p.kill() if kill else p.terminate()
                try:p.wait(5)
                except subprocess.TimeoutExpired:p.kill();p.wait()
            logs.pop(i).close()
        def query(i,path):return clients[i].call('query',path=path)
        def state(i):return json.loads(query(i,'/state').value)
        def account(i,who):return json.loads(query(i,'/account/'+who).value)
        def finalize(i,txs,height):
            return clients[i].call('finalize_block',txs=txs,height=height,
                hash=hashlib.sha256(f'SCRIPTED-ACCOUNT-NOT-CONSENSUS-{height}'.encode()).digest())
        try:
            for i in range(4):start(i)
            checked('four distinct application processes',len({p.pid for p in procs.values()})==4)
            for i in range(4):
                clients[i].call('init_chain',chain_id=genesis['chain_id'],app_state_bytes=canonical(genesis),initial_height=1)
                checked(f'node {i} genesis pins protocol 2',clients[i].call('info').app_version==2)
                checked(f'node {i} newcomer not in genesis',query(i,'/account/'+rid).code!=0)
                checked(f'node {i} proposal opens accounts before dependent transfers',
                    list(clients[i].call('prepare_proposal',txs=block1,height=1,max_tx_bytes=1048576).txs)==block1)
                checked(f'node {i} proposed onboarding not query-visible',query(i,'/account/'+rid).code!=0)
                checked(f'node {i} accepts onboarding proposal',clients[i].call('process_proposal',txs=block1,height=1).status==1)
            results=[finalize(i,block1,1) for i in range(4)]
            checked('onboarding staged root agrees',len({r.app_hash for r in results})==1)
            checked('all opening/grant/spend operations execute',all(all(t.code==0 for t in r.tx_results) for r in results))
            for i in range(4):clients[i].call('commit')
            states=[state(i) for i in range(4)]
            checked('same committed onboarding state',all(s==states[0] for s in states))
            checked('two new accounts now exist',account(0,rid)['balance']==87_980 and account(0,wid)['balance']==74_980)
            checked('two owners have independent same-named grants',len(states[0]['native']['grants'])==2)
            report['blocks'].append({'height':1,'app_hash':states[0]['app_hash'],'transactions':len(block1),'delivery':'scripted'})
            before=state(0)
            for i in range(4):
                checked(f'node {i} accepts rotation and continued operations',clients[i].call('process_proposal',txs=block2,height=2).status==1)
            rotated=[finalize(i,block2,2) for i in range(4)]
            checked('rotation staged roots agree',len({r.app_hash for r in rotated})==1)
            checked('rotation not visible before commit',account(0,rid)['public_key']==public(resident))
            checked('repeated rotation finalization idempotent',finalize(0,block2,2).SerializeToString()==rotated[0].SerializeToString())
            stop(3,kill=True)
            for i in range(3):clients[i].call('commit')
            start(3)
            checked('precommit kill keeps old authorized key',account(3,rid)['public_key']==public(resident))
            checked('precommit restart has previous full state',state(3)==before)
            checked('replay reproduces rotation commitment',finalize(3,block2,2).app_hash==rotated[0].app_hash)
            clients[3].call('commit')
            for i in range(4):
                checked(f'node {i} stable identity now uses new key',account(i,rid)['public_key']==public(new_key))
                checked(f'node {i} prior owner key cannot spend',clients[i].call('check_tx',tx=stale_owner).code!=0)
                checked(f'node {i} old grant cannot spend',clients[i].call('check_tx',tx=stale_agent).code!=0)
                checked(f'node {i} duplicate onboarding cannot reset account',clients[i].call('check_tx',tx=duplicate_open).code!=0)
                checked(f'node {i} original onboarding replay rejected',clients[i].call('check_tx',tx=opened[0]).code!=0)
            stop(0,kill=True);start(0)
            checked('postcommit process restart keeps new key',account(0,rid)['public_key']==public(new_key))
            checked('postcommit restart keeps native grant revocation',clients[0].call('check_tx',tx=stale_agent).code!=0)
            states=[state(i) for i in range(4)];final=states[0]
            checked('four processes agree after crash/replay',all(s==final for s in states))
            checked('exact fixed native supply conserved',sum(row[4] for row in final['native']['accounts'])==1_000_000)
            checked('all eleven operations have receipts',len(final['native']['receipts'])==11)
            checked('rotated account nonce and epoch monotone',account(0,rid)['nonce']==4 and account(0,rid)['epoch']==1)
            grants={row[0]:row for row in final['native']['grants']}
            checked('rotation did not refill prior allowance',grants[rid+'::raven'][6]==12_010)
            checked('other owner allowance remains independent',grants[wid+'::raven'][6]==5_120)
            checked('new native authority has explicitly separate cap',grants[rid+'::raven-v2'][5:7]==[2_020,1_010])
            report['blocks'].append({'height':2,'app_hash':final['app_hash'],'transactions':len(block2),'delivery':'scripted'})
            report['final_state']=final;report['stable_account_id']=rid;report['status']='passed'
        except Exception as exc:
            report['status']='failed';report['error']=f'{type(exc).__name__}: {exc}'
        finally:
            for i in list(procs):stop(i)
            destination.parent.mkdir(parents=True,exist_ok=True)
            for node in runtime.glob('[0-3]'):
                (destination.parent/f'account-node{node.name}.log').write_bytes((node/'server.log').read_bytes())
            report['passed_checks']=sum(c['passed'] for c in report['checks'])
            destination.write_text(json.dumps(report,indent=2)+'\n')
    return report


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--output',type=Path,default=ROOT/'evidence/v05/account-processes.json')
    result=run(p.parse_args().output)
    print(json.dumps({k:result.get(k) for k in ('status','passed_checks','consensus_engine_running','error')}))
    raise SystemExit(0 if result['status']=='passed' else 2)
